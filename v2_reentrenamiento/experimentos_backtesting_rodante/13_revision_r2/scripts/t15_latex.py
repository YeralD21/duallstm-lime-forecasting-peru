def t_respaldo() -> None:
    t5 = leer("T5_SARIMA_sel_Y1_pool.csv")
    t3 = leer("T3_3_SARIMA_sel_Y1_con_regla_pool.csv")
    ord3 = leer("T3_3_regla_respaldo_convergencia.csv")
    ord5 = leer("T5_regla_respaldo_por_ventana.csv")
    err = pd.read_csv(R.BR / "05_predicciones" / "errores_test_promediados_semillas.csv", dtype={"fecha": str})
    cab = [r"Scope & $n$ & SARIMA-sel (protocol) & SARIMA-sel-Y1 (E1, published) & E1 + rule 1 (next by AIC) & "
           r"E1 + rule 2 (next by validation MAE) & DM-HLN $p$, rule 2 vs. best \\"]
    cuerpo = []
    for c in CROPS:
        k = DEC[c]
        x = t5[t5.cultivo == c]
        cuerpo += panel(c, 7, f"best model: {x.mejor.iloc[0]}")
        for a in ALC:
            g = x[x.alcance == a].set_index("modelo")
            r3 = t3[(t3.cultivo == c) & (t3.alcance == a)].iloc[0]
            # controles: las dos tablas del Dia 1 y del Dia 2 deben coincidir
            if not (math.isclose(r3.MAE_SARIMA_sel_Y1_publicado_G7, g.loc["SARIMA-sel-Y1"].MAE, rel_tol=1e-9)
                    and math.isclose(r3.MAE_SARIMA_sel_Y1_alternativa_B, g.loc["SARIMA-sel-Y1-R"].MAE, rel_tol=1e-9)):
                raise SystemExit(f"T3_3 y T5 no coinciden ({c}, {a})")
            pr, y1, rr = g.loc["SARIMA-sel"], g.loc["SARIMA-sel-Y1"], g.loc["SARIMA-sel-Y1-R"]
            cuerpo.append(f"{ALC[a]} & {int(pr.n_meses)} & {vci(pr.MAE, pr.IC_lo, pr.IC_hi, k)} & {vci(y1.MAE, y1.IC_lo, y1.IC_hi, k)} & "
                          f"{f(r3.MAE_SARIMA_sel_Y1_con_regla, k)} & {vci(rr.MAE, rr.IC_lo, rr.IC_hi, k)} & {p(rr.DM_p)} \\\\")
        r3 = t3[(t3.cultivo == c) & (t3.alcance == "todos")].iloc[0]
        if not nan(r3.MAE_2021_publicado):
            e = err[(err.modelo == "SARIMA-sel") & (err.cultivar == c) & (err.anio_test == 2021)]
            cuerpo.append(f"2021 window only & {len(e)} & {f(e.ae.mean(), k)} & {f(r3.MAE_2021_publicado, k)} & "
                          f"{f(r3.MAE_2021_con_regla, k)} & {f(r3.MAE_2021_alternativa_B, k)} & --- \\\\")
        cuerpo.append(r"\midrule")
    o3 = ord3[ord3.regla_aplicada.astype(str) == "True"].iloc[0]
    o5 = ord5[ord5.E1_respaldo_usado.astype(str) == "True"].iloc[0]
    if (o3.cultivo, int(o3.anio_test)) != (o5.cultivo, int(o5.anio_test)) or len(ord3[ord3.regla_aplicada.astype(str) == "True"]) != 1:
        raise SystemExit("La regla de respaldo deberia actuar en una sola unidad, la misma en T3_3 y T5")
    notas = ("E1 (SARIMA-sel-Y1): the order chosen by SARIMA-sel is refitted with data up to $Y-1$. In the original protocol all ten "
             "SARIMA-sel fits converge, so neither rule changes any published result. In E1 only one unit does not converge: "
             f"{o3.cultivo} {int(o3.anio_test)}, chosen order {o3.orden_elegido} (AIC rank {int(o3.posicion_aic_elegido)} of 5). "
             f"Rule 1: next order in AIC rank among the five preselected that converges: {o3.orden_respaldo} (AIC rank "
             f"{int(o3.posicion_aic_respaldo)}). Rule 2: next order by validation MAE among those that converge (the protocol's "
             f"selection criterion): {o5.E1_orden_final} (AIC rank {int(o5.E1_posicion_aic_final)}). The MAE in shock months does "
             f"not change because the {o3.cultivo} {int(o3.anio_test)} window has no P75 shock month. Rule 1 is shown without CI "
             "(its forecasts were not stored; MAE from the round-2 day-1 analysis). Rule 2 keeps the protocol's selection "
             f"criterion. {LEG_CI} {POST}")
    escribir("tab_r2_sarima_sel_fallback.tex", tabla(
        r"Experiment E1 (SARIMA-sel-Y1) with the two fallback rules for a non-converging fit (pool 2021--2025).",
        "tab:r2_sarima_sel_fallback", "lrrrrrr", cab, quitar_ultimo_midrule(cuerpo), notas))


