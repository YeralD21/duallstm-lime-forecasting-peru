def t_crps() -> None:
    d = leer("T10_crps_resumen.csv")
    pm = leer("T10_crps_por_mes.csv")
    met = {"CRPS_Q": "CRPS (quantiles)", "twCRPS_Q": "Threshold-weighted CRPS", "CRPS_normal_exacto": "CRPS, exact Gaussian"}
