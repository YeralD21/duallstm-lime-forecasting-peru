def t_ranking() -> None:
    rkg = leer("T1_ranking_shock_P50_P90.csv")
    rob = leer("T1_robustez_3de4.csv")
    pcts = [50, 60, 75, 90]
    cab = [r" & \multicolumn{6}{c}{Shock months, MoM change} & \multicolumn{6}{c}{Shock months, YoY change} \\",
           r"\cmidrule(lr){2-7}\cmidrule(lr){8-13}",
           "Model & " + " & ".join([f"P{q}" for q in pcts] + ["Top (of 4)", "Consistently"]) + " & "
           + " & ".join([f"P{q}" for q in pcts] + ["Top (of 4)", "Consistently"]) + r" \\"]
    cuerpo, extra_notas = [], []
    for c in CROPS:
        g = rkg[(rkg.grupo == "12_modelos") & (rkg.cultivo == c)]
        b = rob[(rob.grupo == "12_modelos") & (rob.cultivo == c)].set_index(["definicion", "modelo"])
        n = {dfn: "/".join(str(int(g[(g.definicion == dfn) & (g.percentil == q)].n_meses.iloc[0])) for q in pcts) for dfn in ("MoM", "YoY")}
        cuerpo += panel(c, 13, f"shock months at P50/P60/P75/P90: MoM {n['MoM']}; YoY {n['YoY']}")
        for m in g.modelo.drop_duplicates():
            celdas = [mod(m)]
            for dfn in ("MoM", "YoY"):
                for q in pcts:
                    r = g[(g.definicion == dfn) & (g.percentil == q) & (g.modelo == m)].iloc[0]
                    celdas.append(rk(r.posicion, r.primero))
                rb = b.loc[(dfn, m)]
                celdas += [str(int(rb.n_primero_de_4)), si(rb.consistently_top_ranked)]
            cuerpo.append(" & ".join(celdas) + r" \\")
        cuerpo.append(r"\midrule")
        for dfn in ("MoM", "YoY"):
            r10 = rob[(rob.grupo == "10_modelos") & (rob.cultivo == c) & (rob.definicion == dfn) & rob.consistently_top_ranked].modelo.tolist()
            r12 = b.loc[dfn][b.loc[dfn].consistently_top_ranked].index.tolist()
            extra_notas.append(f"{c} {dfn}: {', '.join(r12) or 'none'} (12 models) vs. {', '.join(r10) or 'none'} (10 pre-registered models)")
    notas = (f"Position by MAE in the shock months of each threshold (pool 2021--2025). {LEG_STAR} "
             "Consistently top-ranked = first or tied in at least 3 of the 4 thresholds (pre-registered rule, amendment E-BR1). "
             f"{DAG} Added after the protocol. Consistently top-ranked models: " + "; ".join(extra_notas) + ". " + POST)
    escribir("tab_r2_ranking.tex", tabla(
        r"Ranking by MAE in shock months at four thresholds with twelve models (ten pre-registered plus ETS$^{\dagger}$ and "
        r"Theta$^{\dagger}$), test windows 2021--2025.", "tab:r2_ranking_consistently_top", "l" + "c" * 12, cab,
        quitar_ultimo_midrule(cuerpo), notas))


