def leer(nombre: str) -> pd.DataFrame:
    return pd.read_csv(RES / nombre, dtype={"fecha": str})


def nan(x) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x)) or (x is pd.NA)


def f(x, d: int) -> str:
    if nan(x):
        return "---"
    s = f"{abs(float(x)):,.{d}f}"
    return ("$-$" if float(x) < 0 and float(s.replace(",", "")) != 0 else "") + s


def ci(lo, hi, d: int) -> str:
    return "---" if nan(lo) or nan(hi) else f"[{f(lo, d)}; {f(hi, d)}]"


def vci(v, lo, hi, d: int) -> str:
    return f"{f(v, d)} {ci(lo, hi, d)}" if not nan(lo) else f(v, d)


def p(x) -> str:
    return "---" if nan(x) else ("$<$0.001" if float(x) < 0.001 else f"{float(x):.3f}")


def mod(m: str) -> str:
    return m + (DAG if m in NEW else "")


def rk(pos, primero) -> str:
    return "---" if nan(pos) else f"{int(pos)}{'*' if bool(primero) else ''}"


def si(x) -> str:
    return r"\textbf{Yes}" if bool(x) else "No"


def panel(c: str, ncol: int, extra: str = "") -> list[str]:
    return [rf"\multicolumn{{{ncol}}}{{l}}{{\textbf{{{CROP[c]}}}{(': ' + extra) if extra else ''}}} \\", r"\midrule"]


def tabla(caption: str, label: str, colspec: str, cabecera: list[str], cuerpo: list[str], notas: str) -> str:
    L = [r"\begin{table}[H]", r"\centering", r"\scriptsize", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
         r"\resizebox{\linewidth}{!}{%", rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", *cabecera, r"\midrule",
         *cuerpo, r"\bottomrule", r"\end{tabular}%", "}", r"\par\vspace{3pt}",
         rf"{{\footnotesize\raggedright {notas}\par}}", r"\end{table}"]
    return "\n".join(L)


def escribir(nombre: str, *tablas: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    cab = (f"% {nombre}: generated by 13_revision_r2/scripts/t15_latex.py from 13_revision_r2/resultados/*.csv; do not edit by hand.\n"
           "% Requires \\usepackage{booktabs,graphicx,float}.\n")
    (OUT / nombre).write_text(cab + "\n\n".join(tablas) + "\n", encoding="utf-8", newline="\n")
    print(f"latex/{nombre}")


def quitar_ultimo_midrule(cuerpo: list[str]) -> list[str]:
    while cuerpo and cuerpo[-1] in (r"\midrule", r"\addlinespace"):
        cuerpo.pop()
    return cuerpo


